import type { Drift3DLandmark } from "@/lib/drift3dLandmarks";
import { drift3dTrackNodeBySlug } from "@/lib/drift3dTopology";

function origin(slug: string) {
  const node = drift3dTrackNodeBySlug[slug];

  if (!node) {
    throw new Error(`Missing DRIFT node for new track landmark: ${slug}`);
  }

  return { x: node.position.x, z: node.position.z };
}

